#!/usr/bin/env python3
"""Write docs/metrics.md: every series name the profiles can export, grouped by profile."""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import profiles as P  # noqa: E402
import promql  # noqa: E402

OUT = P.REPO / "docs" / "metrics.md"

HEADER = """# Metrics catalog

Generated by `scripts/metrics_catalog.py` from `design_profile/`. Do not edit by hand.

These names are derived from the profiles, not observed on a router. See
[juniper-caveats.md](juniper-caveats.md) before building on a name that no dashboard uses yet.

- `counter` series are cumulative and carry the OTLP `_total` suffix. Query them with `rate()` or `increase()`.
- `gauge` series are the last sampled value.
- Fields that arrive as strings (state, vendor, model) are exported as a gauge with value `1` and the
  text in a `value` label, for example `junos_network_instance_bgp_session_state{value="ESTABLISHED"}`.
- Every series carries `job="openjts"`, `instance` (the collector name) and `device` (the router name
  from `targets/routers.yaml`). Per-router metadata is in `junos_device_info`.
- The list comes from each profile's field allowlist, so it is an upper bound. A series only exists
  if the router family and Junos release actually stream that leaf.

"""


def main() -> int:
    spec = promql.spec()
    by_profile: dict[str, set[str]] = {}
    for path in P.all_confs():
        profile = path.relative_to(P.PROFILE_DIR).parts[0]
        by_profile.setdefault(profile, set()).update(P.conf_measurements(P.load_conf(path)))

    lines = [HEADER]
    total = set()
    for profile in sorted(by_profile):
        rows = []
        for meas in sorted(by_profile[profile]):
            entry = spec.get(meas)
            if not entry:
                continue
            for field in entry["keep"]:
                name = promql.series_name(meas, field)
                kind = "counter" if field in entry["counters"] else "gauge"
                rows.append((name, kind, meas))
        if not rows:
            continue
        lines.append(f"## {profile}\n")
        lines.append("| Series | Type | Influx measurement |")
        lines.append("|---|---|---|")
        for name, kind, meas in sorted(set(rows)):
            lines.append(f"| `{name}` | {kind} | {meas} |")
            total.add(name)
        lines.append("")

    lines.append("## Collector metadata\n")
    lines.append("| Series | Type | Labels |")
    lines.append("|---|---|---|")
    lines.append("| `junos_device_info` | gauge (always 1) | device, family, version, model, site, profiles |")
    lines.append("")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(P.REPO).as_posix()}: {len(total)} series across {len(by_profile)} profiles")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
